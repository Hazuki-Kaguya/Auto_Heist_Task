    # 差事异常处理
    def aht_heist_error(self):
        self.log_error(f"{self.label}自动执行差事中异常，将退出差事重试")
        self.error += 1
        self.log_info(f"{self.label}：执行跳出操作，尝试跳出")
        self.send_key('esc', down_time=0.15)
        self.sleep(0.20)
        if self.wait_ocr(x=0.46, y=0.32, to_x=0.54, to_y=0.37, match=re.compile("确认退出"), time_out=2.0):
            self.wait_click_ocr(x=0.52, y=0.63, to_x=0.68, to_y=0.68, match=re.compile("确认"), time_out=1.0)
